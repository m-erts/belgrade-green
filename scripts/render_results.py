"""Collect every number used in the README, posts and figures into one JSON and docs/RESULTS.md."""
import json

import numpy as np
import pandas as pd

from bgreen.config import INTERIM, ROOT, TABLES


def conn_block(run):
    d = INTERIM / f"conn_{run}"
    if not (d / "summary.json").exists():
        return None
    s = json.loads((d / "summary.json").read_text())
    out = {"n_patches": s["n_patches"], "habitat_ha": round(s["habitat_ha"], 1),
           "tree_cover_aoi_ha": round(s["tree_cover_aoi_ha"], 1),
           "ec_ha": {k: round(v, 1) for k, v in s["ec_ha"].items()},
           "ec_share": {k: round(v / s["habitat_ha"], 4) for k, v in s["ec_ha"].items()},
           "ec_no_links_ha": round(s["ec_no_links_ha"], 1), "n_links": s["n_links"]}
    return out


def main():
    K = {"connectivity": {}, "measures": {}, "landscape": {}}
    for run in ["main", "nodes_touching", "permeable", "strict", "water_barrier", "min05ha",
                "city", "city_min05ha", "city_permeable", "city_strict"]:
        b = conn_block(run)
        if b:
            K["connectivity"][run] = b
    for run in ["main", "nodes_touching", "city", "city_touching"]:
        d = INTERIM / f"conn_{run}"
        if (d / "buildover.parquet").exists() and (d / "patch_names.parquet").exists():
            bo = pd.read_parquet(d / "buildover.parquet").merge(pd.read_parquet(d / "patch_names.parquet"), on="patch")
            K["connectivity"][f"{run}_buildover"] = bo.sort_values("EC_loss_1000", ascending=False).round(3).to_dict("records")
        if (d / "pinchpoints.csv").exists():
            K["connectivity"][f"{run}_pinchpoints"] = pd.read_csv(d / "pinchpoints.csv").round(4).to_dict("records")
    d = INTERIM / "conn_city"
    if (d / "link_importance.parquet").exists():
        li = pd.read_parquet(d / "link_importance.parquet").sort_values("dLink_1000", ascending=False).head(10)
        K["connectivity"]["city_top_links"] = li.round(3).to_dict("records")
    d = INTERIM / "conn_city"
    if (d / "patch_names.parquet").exists():
        from bgreen.connectivity import pc
        names = pd.read_parquet(d / "patch_names.parquet")
        a = np.load(d / "areas.npy")
        D = pc.apsp(pc.adjacency(len(a), pd.read_parquet(d / "links.parquet")))
        imp = pd.read_parquet(d / "node_importance.parquet").set_index("patch")
        def pid(name):
            m = names[names.green_name.fillna("").str.contains(name, regex=False)]
            return int(m.assign(a=a[m.patch - 1]).sort_values("a").patch.iloc[-1]) if len(m) else None
        parks = {}
        kos = pid("Košutnjak")
        for nm in ["Veliki Kalemegdan", "Tašmajdan", "Park Ušće"]:
            p = pid(nm)
            if p and kos:
                parks[nm] = {"patch": p, "area_ha": float(a[p - 1]), "dPC_1000": float(imp.loc[p, "dPC_1000"]),
                             "cost_to_kosutnjak": float(D[p - 1, kos - 1])}
        K["connectivity"]["city_central_parks"] = parks
    lm = pd.read_csv(TABLES / "landscape_metrics.csv").set_index("scope")
    K["landscape"] = lm.round(3).to_dict("index")
    um = pd.read_csv(TABLES / "units_measures.csv")
    K["measures"]["units"] = um.round(4).to_dict("records")
    K["measures"]["city"] = json.loads((TABLES / "city_access.json").read_text())
    (TABLES / "key_numbers.json").write_text(json.dumps(K, indent=1, ensure_ascii=False, default=float))
    lines = ["# Results", "", "Generated by `scripts/render_results.py`. Do not edit by hand.", ""]
    lines += ["## Part 1. Connectivity", "", "| run | patches | habitat, ha | EC at 1 km, ha | EC / habitat |", "|---|---:|---:|---:|---:|"]
    for run, b in K["connectivity"].items():
        if isinstance(b, dict) and "ec_ha" in b:
            lines.append(f"| {run} | {b['n_patches']:,} | {b['habitat_ha']:,.0f} | {b['ec_ha']['1000']:,.0f} | {b['ec_share']['1000']:.1%} |")
    for run in ["main", "nodes_touching", "city", "city_touching"]:
        key = f"{run}_buildover"
        if key in K["connectivity"]:
            bo = pd.DataFrame(K["connectivity"][key])[["patch", "area_ha", "EC_loss_1000", "EC_loss_pct_1000",
                                                         "leverage_1000", "green_name", "near_place"]].head(12)
            lines += ["", f"### Build-over scenarios, run `{run}` (d50 = 1 km)", "", bo.to_markdown(index=False)]
    lm = pd.read_csv(TABLES / "landscape_metrics.csv")
    lines += ["", "### Landscape metrics (tree cover)", "", lm.round(2).to_markdown(index=False)]
    lines += ["", "## Part 2. Measures by unit", "", um.round(3).to_markdown(index=False)]
    lines += ["", "City-wide access measures:", "", "```", json.dumps(K["measures"]["city"], indent=1), "```"]
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("written", TABLES / "key_numbers.json")


if __name__ == "__main__":
    main()
